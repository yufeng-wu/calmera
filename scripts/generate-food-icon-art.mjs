// Regenerates lib/foodIconArt.mjs from assets/food-icons/*.svg.
// Usage: node scripts/generate-food-icon-art.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const source = new URL("../assets/food-icons/", import.meta.url);
const target = new URL("../lib/foodIconArt.mjs", import.meta.url);

function compactSvg(svg) {
  return svg.replace(/<!--[\s\S]*?-->/g, "").replace(/>\s+</g, "><").replace(/\s+/g, " ").trim();
}

const entries = readdirSync(source).filter(name => name.endsWith(".svg")).sort()
  .map(name => [name.slice(0, -4), compactSvg(readFileSync(new URL(name, source), "utf8"))]);

writeFileSync(target, `// Generated by scripts/generate-food-icon-art.mjs from assets/food-icons. Do not edit.
// Original Calmera drawings for foods Unicode has no emoji for.
export const FOOD_ICON_ART = Object.freeze({
${entries.map(([key, svg]) => `  ${JSON.stringify(key)}: ${JSON.stringify(svg)},`).join("\n")}
});
`);
console.log(`Wrote ${entries.length} drawings`);
